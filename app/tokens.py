"""Generate synthetic HS256 JWT tokens for local development and testing.

NOTE: Long-lived local tokens generated by this module are strictly for local demo and
automated testing purposes. Never use static HS256 keys or long-lived tokens in production.
"""

import json
import uuid
from datetime import UTC, datetime, timedelta

import jwt

from app.config import get_settings
from app.models import UserRole
from app.seed import (
    ADMIN_USER_ID,
    CONFLICTED_REVIEWER_USER_ID,
    HAWAII_OFFICE_USER_ID,
    MEMBER_USER_ID,
    OFFICE_USER_ID,
    REVIEWER_USER_ID,
    SECOND_REVIEWER_USER_ID,
)


def mint_token(
    *,
    user_id: uuid.UUID,
    role: UserRole,
    issued_at: datetime | None = None,
    expires_in: timedelta | None = None,
) -> str:
    settings = get_settings()
    iat = issued_at if issued_at is not None else datetime.now(UTC)
    ttl = expires_in if expires_in is not None else timedelta(hours=settings.jwt_access_token_expire_hours)
    exp = iat + ttl
    payload = {
        "sub": str(user_id),
        "role": role.value,
        "iss": settings.jwt_issuer,
        "aud": settings.jwt_audience,
        "iat": int(iat.timestamp()),
        "exp": int(exp.timestamp()),
    }
    return jwt.encode(payload, settings.jwt_secret_key, algorithm=settings.jwt_algorithm)


def generate_demo_tokens() -> dict[str, str]:
    now_anchor = datetime.now(UTC)
    ttl = timedelta(days=365)
    return {
        "office": mint_token(
            user_id=OFFICE_USER_ID, role=UserRole.OFFICE, issued_at=now_anchor, expires_in=ttl
        ),
        "hawaii_office": mint_token(
            user_id=HAWAII_OFFICE_USER_ID, role=UserRole.OFFICE, issued_at=now_anchor, expires_in=ttl
        ),
        "member": mint_token(
            user_id=MEMBER_USER_ID, role=UserRole.MEMBER, issued_at=now_anchor, expires_in=ttl
        ),
        "reviewer": mint_token(
            user_id=REVIEWER_USER_ID, role=UserRole.REVIEWER, issued_at=now_anchor, expires_in=ttl
        ),
        "conflicted_reviewer": mint_token(
            user_id=CONFLICTED_REVIEWER_USER_ID,
            role=UserRole.REVIEWER,
            issued_at=now_anchor,
            expires_in=ttl,
        ),
        "second_reviewer": mint_token(
            user_id=SECOND_REVIEWER_USER_ID,
            role=UserRole.REVIEWER,
            issued_at=now_anchor,
            expires_in=ttl,
        ),
        "admin": mint_token(
            user_id=ADMIN_USER_ID, role=UserRole.ADMIN, issued_at=now_anchor, expires_in=ttl
        ),
    }


def main() -> None:
    print(json.dumps(generate_demo_tokens(), indent=2))


if __name__ == "__main__":
    main()
